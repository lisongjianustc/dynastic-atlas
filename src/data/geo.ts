/**
 * 共享边界链（boundary chain）库。
 *
 * 设计要点：相邻政权的交界在历史上是同一条线。若各画各的，两个面之间会露出
 * 缝隙或重叠。因此这里把每条边界只写一次，各政权按固定方向拼接复用。
 *
 * 方向约定：链名后缀 N/S/E/W 表示走向，rev() 反接。
 * 所有坐标 WGS84 [lon, lat]，精度刻意压到 0.1° 级 —— P0 阶段全部标 borderPrecision=1。
 */

export type Pt = [number, number];

export const rev = (p: Pt[]): Pt[] => [...p].reverse();

/** 拼接若干边界链为闭合外环（自动去重相邻重复点、自动闭合） */
export const ring = (...parts: (Pt[] | number[][])[]): Pt[] => {
  const out: Pt[] = [];
  for (const part of parts) {
    for (const pt of part) {
      const x = pt[0];
      const y = pt[1];
      const last = out[out.length - 1];
      if (!last || last[0] !== x || last[1] !== y) out.push([x, y]);
    }
  }
  const first = out[0];
  const last = out[out.length - 1];
  if (out.length > 1 && (first[0] !== last[0] || first[1] !== last[1])) out.push([first[0], first[1]]);
  return out;
};

