export type Pt = [number, number];

export const rev = (p: Pt[]): Pt[] => [...p].reverse();

/**
 * 从一条链上截取两个锚点之间的一段（按最近顶点切）。
 * 真实区域的外环动辄五六十点，按下标切片既难读又容易切错，
 * 用地理锚点说话清楚得多。
 */
export const arc = (chain: Pt[], from: Pt, to: Pt): Pt[] => {
  const near = (p: Pt) => {
    let bi = 0;
    let bd = Infinity;
    chain.forEach((q, i) => {
      const d = (q[0] - p[0]) ** 2 + (q[1] - p[1]) ** 2;
      if (d < bd) (bd = d), (bi = i);
    });
    return bi;
  };
  const i = near(from);
  const j = near(to);
  return i <= j ? chain.slice(i, j + 1) : chain.slice(j, i + 1).reverse();
};

/** 拼接若干边界链为闭合外环（自动去重相邻重复点、自动闭合） */
export const ring = (...parts: (Pt[] | number[][])[]): Pt[] => {
  const out: Pt[] = [];
  for (const part of parts) {
    for (const pt of part) {
      const x = pt[0];
      const y = pt[1];
      const last = out[out.length - 1];
      if (!last || last[0] !== x || last[1] !== y) out.push([x, y]);
    }
  }
  const first = out[0];
  const last = out[out.length - 1];
  if (out.length > 1 && (first[0] !== last[0] || first[1] !== last[1])) out.push([first[0], first[1]]);
  return out;
};

